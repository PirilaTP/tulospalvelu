"""C-9 step 2: generate the isolated probe projects C9ProbeHk and C9ProbeJuk
(same method as C-6 step 2 and C-8, todisteet/c8/koeohjelmat).

Copies VS/Tests/TpCoreHk.vcxproj and TpCoreJuk.vcxproj (same production
sources, defines and options, both Release and Asan configurations),
rewrites the relative paths for this directory and replaces the test-source
list with CoreMain.cpp, the fixtures and this directory's probe file.
C9ProbeJuk's probe file includes Juk/VTulostus.cpp itself, as
Tests/core/VTulostusTests.cpp does (TpCoreJuk leaves it out of its source
list). Nothing under TPsource/ is changed.
Usage: python -I tee_projektit.py   (run from this directory)
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, '..', '..', '..', '..', '..', '..'))
V52 = os.path.join(REPO, 'TPsource', 'V52')
UP = '..\\' * 6                     # this directory -> repo root
assert os.path.isdir(os.path.join(V52, 'VS', 'Tests')), V52

PROBES = {'TpCoreHk': ('C9ProbeHk', 'c9_hk_probes.cpp', 'HkFixture.cpp', '001'),
          'TpCoreJuk': ('C9ProbeJuk', 'c9_juk_probes.cpp', 'VFixture.cpp', '002')}

for src, (name, probe, fixture, guid) in PROBES.items():
    with open(os.path.join(V52, 'VS', 'Tests', src + '.vcxproj'), encoding='utf-8-sig') as f:
        t = f.read()
    t = t.replace('..\\..\\..\\..\\TPexe', '@ROOT@TPexe')
    t = t.replace('"..\\..\\', '"' + UP + 'TPsource\\V52\\')
    t = t.replace('>..\\..\\', '>' + UP + 'TPsource\\V52\\')
    t = t.replace(';..\\..\\', ';' + UP + 'TPsource\\V52\\')
    t = t.replace('@ROOT@', UP)
    t = t.replace('TP_CORE_NAME=' + src, 'TP_CORE_NAME=' + name)
    t = t.replace('<TargetName>' + src, '<TargetName>' + name)
    t = t.replace('<RootNamespace>' + src, '<RootNamespace>' + name)
    t = re.sub(r'<ProjectGuid>\{[^}]+\}', '<ProjectGuid>{00000000-0000-4000-8000-0000000c9' + guid + '}', t)
    tests = re.search(r'(<ItemGroup>\s*<ClCompile Include="[^"]*Tests\\core\\CoreMain\.cpp" />.*?</ItemGroup>)', t, re.S)
    assert tests, src
    core = UP + 'TPsource\\V52\\Tests\\'
    items = ['core\\CoreMain.cpp', 'fixtures\\TpCore.cpp', 'fixtures\\TpCrash.cpp',
             'fixtures\\TpNet.cpp', 'fixtures\\' + fixture]
    block = '<ItemGroup>\n' + ''.join('    <ClCompile Include="%s%s" />\n' % (core, i) for i in items) + \
            '    <ClCompile Include="%s" />\n  </ItemGroup>' % probe
    t = t.replace(tests.group(1), block)
    t = re.sub(r'<!--.*?-->', '<!-- C-9 step 2 probe project generated by tee_projektit.py from '
               'VS/Tests/%s.vcxproj; do not edit. Build with rakenna.cmd. -->' % src, t, count=1, flags=re.S)
    with open(os.path.join(HERE, name + '.vcxproj'), 'w', encoding='utf-8', newline='\r\n') as f:
        f.write(t)
    print('wrote', name + '.vcxproj')
